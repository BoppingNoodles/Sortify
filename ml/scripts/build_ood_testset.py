def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def build(out_dir: Path) -> list[dict[str, str]]:
    """Write all images and the manifest; return the manifest rows."""
    out_dir.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(SEED)
    rows = []
    for filename, group, source, description, factory in build_specs(
        load_sources(), rng
    ):
        path = out_dir / filename
        factory().convert("RGB").save(path, format="PNG")
        rows.append(
            {
                "filename": filename,
                "group": group,
                "source": source,
                "license": LICENSES[source],
                "description": description,
                "sha256": sha256_file(path),
            }
        )
    with (out_dir / "manifest.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=MANIFEST_FIELDS)
        writer.writeheader()
        writer.writerows(rows)
    return rows


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    args = parser.parse_args(argv)
    rows = build(args.out_dir)
    print(f"[*] Wrote {len(rows)} images and manifest.csv to {args.out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
